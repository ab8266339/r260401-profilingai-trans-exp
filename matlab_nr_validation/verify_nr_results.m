function verify_nr_results(profile, options)
%VERIFY_NR_RESULTS Verify one complete, independently published case shard.

arguments
    profile (1,1) string {mustBeMember(profile, ...
        ["smoke", "quick", "medium", "formal"])}
    options.OutputRoot (1,1) string
end

outputRoot = options.OutputRoot;
cfg = nr_validation_config(profile);
requiredFiles = ["summary.csv", "paired_differences.csv", ...
    "paired_ci95.csv", "summary.json", "results.mat", ...
    "case_manifest.json"];
for name = requiredFiles
    assert(isfile(fullfile(outputRoot, name)), "Missing %s", name);
end

t = readtable(fullfile(outputRoot, "summary.csv"), TextType="string");
required = ["experiment_version", ...
    "cohort_completed_mean_ul_latency_ms", ...
    "cohort_completed_p95_ul_latency_ms", "cohort_latency_reliable", ...
    "cohort_completion_fraction_packets", ...
    "cohort_attempted_packet_count_mismatch", ...
    "attempted_offered_mbps", "accepted_offered_mbps", ...
    "cohort_delivered_mbps_normalized_by_generation_window", ...
    "receiver_window_conditional_mean_ul_latency_ms", ...
    "receiver_window_conditional_p95_ul_latency_ms", ...
    "receiver_window_latency_reliable", ...
    "warmup_end_tx_rx_byte_imbalance", ...
    "window_tx_rx_byte_imbalance", "run_end_tx_rx_byte_imbalance", ...
    "bler", "cohort_app_queue_overflow_rate", ...
    "rlc_reassembly_pdu_drop_fraction", ...
    "harq_retransmissions", "ul_new_tx_rbs", ...
    "ul_mcs_mean_grant_weighted", "ul_mcs_mean_prb_weighted", ...
    "ul_mcs_distribution_reliable", "link_state_checksum", ...
    "los_ues", "nlos_ues", "mean_path_loss_db", "std_shadow_db"];
assert(all(ismember(required, string(t.Properties.VariableNames))), ...
    "Output schema is incomplete.");
assert(height(t) == 2, "A case shard must contain exactly two arms.");
assert(all(t.profile == profile));
assert(all(t.experiment_version == cfg.ExperimentVersion));
assert(all(t.cohort_attempted_packet_count_mismatch == 0));
assert(all(t.priming_marker_packets == t.total_ues));
assert(all(t.priming_marker_bytes == t.total_ues));
assert(all(t.priming_marker_excluded_from_cohort));
assert(all(t.cohort_accepted_packets > 0));
assert(all(t.cohort_completed_packets > 0));
assert(all(t.cohort_completed_packets <= t.cohort_accepted_packets));
assert(all(t.cohort_completed_bytes <= t.cohort_accepted_bytes));
assert(all(t.cohort_completion_fraction_packets >= 0 & ...
    t.cohort_completion_fraction_packets <= 1));
assert(all(isfinite(t.cohort_completed_mean_ul_latency_ms) & ...
    t.cohort_completed_mean_ul_latency_ms >= 0));
assert(all(isfinite(t.cohort_completed_p95_ul_latency_ms) & ...
    t.cohort_completed_p95_ul_latency_ms >= 0));
assert(all(t.cohort_latency_reliable));
assert(all(t.receiver_window_rx_packets > 0));
assert(all(t.receiver_window_latency_reliable));
assert(all(t.receiver_window_latency_sample_count == ...
    t.receiver_window_rx_packets));
assert(all(isfinite(t.attempted_offered_mbps) & ...
    t.attempted_offered_mbps >= 0));
assert(all(isfinite(t.accepted_offered_mbps) & ...
    t.accepted_offered_mbps >= 0));
assert(all(isfinite(t.cohort_delivered_mbps_normalized_by_generation_window) & ...
    t.cohort_delivered_mbps_normalized_by_generation_window >= 0));
assert(all(t.drain_new_app_tx_packets == 0));
assert(all(t.drain_new_app_tx_bytes == 0));
assert(all(t.drain_new_app_queue_overflow_packets == 0));
assert(all(t.bler >= 0 & t.bler <= 1));
assert(all(t.rlc_reassembly_pdu_drop_fraction >= 0 & ...
    t.rlc_reassembly_pdu_drop_fraction <= 1));
assert(all(t.los_ues + t.nlos_ues == t.total_ues));
assert(all(isfinite(t.mean_path_loss_db)));
assert(all(isfinite(t.std_shadow_db) & t.std_shadow_db >= 0));
assert(all(t.ul_mcs_distribution_reliable));

assert(isequal(sort(t.full_ul_slots)', [4 11]));
assert(isscalar(unique(t.background_ues)));
assert(isscalar(unique(t.seed)));
assert(isscalar(unique(t.traffic_packet_checksum)));
assert(isscalar(unique(t.traffic_interval_checksum)));
assert(isscalar(unique(t.position_checksum)));
assert(isscalar(unique(t.link_state_checksum)));
assert(isscalar(unique(t.los_ues)));
assert(isscalar(unique(t.mean_path_loss_db)));

links = readtable(fullfile(outputRoot, "link_states", ...
    "link_state.csv"), TextType="string");
assert(height(links) == t.total_ues(1));
assert(sum(links.is_los) == t.los_ues(1));
assert(all(isfinite(links.total_path_loss_db)));

for idx = 1:height(t)
    arm = t.arm(idx);
    mcsPath = fullfile(outputRoot, "arm_audits", ...
        "ul_mcs_histogram_" + arm + ".csv");
    latencyPath = fullfile(outputRoot, "arm_audits", ...
        "sdu_latencies_" + arm + ".csv");
    assert(isfile(mcsPath));
    assert(isfile(latencyPath));
    mcs = readtable(mcsPath, TextType="string");
    latency = readtable(latencyPath, TextType="string");
    assert(height(mcs) == 28);
    assert(sum(mcs.grant_count) == t.ul_mcs_grant_count(idx));
    assert(sum(mcs.scheduled_prb_count) == ...
        t.ul_mcs_total_scheduled_prbs(idx));
    assert(sum(latency.in_receiver_window) == ...
        t.receiver_window_latency_sample_count(idx));
    assert(sum(latency.in_completed_measurement_generated_cohort) == ...
        t.cohort_completed_packets(idx));
end

paired = readtable(fullfile(outputRoot, "paired_differences.csv"), ...
    TextType="string");
assert(height(paired) == 1);
assert(all(ismember(["delta_cohort_completed_mean_latency_ms", ...
    "delta_cohort_completed_p95_latency_ms", ...
    "cohort_completed_p95_latency_reduction_pct", ...
    "delta_cohort_delivered_mbps_normalized_by_generation_window", ...
    "delta_ul_mcs_mean_grant_weighted"], ...
    string(paired.Properties.VariableNames))));

ci95 = readtable(fullfile(outputRoot, "paired_ci95.csv"), ...
    TextType="string");
assert(~isempty(ci95));
assert(all(ci95.num_paired_seeds == 1));
fprintf("Verification passed: %s (one paired shard).\n", outputRoot);
end
